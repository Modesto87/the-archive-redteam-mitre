export function translateTechnicalProse(text) {
  if (!text) return '';

  // Proteger blocos de código <code>...</code> e `...` durante a tradução
  const codePlaceholders = [];
  let protectedText = text.replace(/<code>[\s\S]*?<\/code>|`[^`]+`/g, (match) => {
    codePlaceholders.push(match);
    return `__CODE_BLOCK_${codePlaceholders.length - 1}__`;
  });

  // Limpar citações (Citation: ...) mantendo registo limpo
  protectedText = protectedText.replace(/\(Citation:\s*([^)]+)\)/g, ' `[Ref: $1]`');

  // Converter links markdown do MITRE para formato limpo
  protectedText = protectedText.replace(/\[([^\]]+)\]\(https:\/\/attack\.mitre\.org\/(?:techniques|tactics|software|groups|mitigations)\/([^)]+)\)/g, (_, label, id) => {
    const cleanId = id.replace(/\//g, '.');
    return `**${label}** (\`${cleanId}\`)`;
  });

  // Aplicar regras de tradução técnica
  for (const [regex, replacement] of PROSE_RULES) {
    protectedText = protectedText.replace(regex, replacement);
  }

  // Restaurar blocos de código intocados
  protectedText = protectedText.replace(/__CODE_BLOCK_(\d+)__/g, (_, index) => {
    const raw = codePlaceholders[Number(index)];
    return raw.replace(/<\/?code>/g, '`');
  });

  return protectedText.trim();
}
